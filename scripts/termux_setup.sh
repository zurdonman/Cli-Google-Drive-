#!/data/data/com.termux/files/usr/bin/bash
# Build glotlabs/gdrive natively for Android ARM64 in a Debian proot.
set -Eeuo pipefail

RELEASE="${GDRIVE_RELEASE:-3.9.1}"
DISTRO="${GDRIVE_PROOT_DISTRO:-debian}"
JOBS="${GDRIVE_BUILD_JOBS:-2}"
INSTALL_DIR="${GDRIVE_INSTALL_DIR:-${XDG_DATA_HOME:-$HOME/.local/share}/google-drive-skill/bin}"

fail() {
    printf 'Error: %s\n' "$*" >&2
    exit 1
}

[ "$(uname -m)" = "aarch64" ] || fail "Este instalador es exclusivo para Android ARM64 (aarch64); detectado: $(uname -m)."
case "${PREFIX:-}" in
    */com.termux/files/usr) ;;
    *) fail "Ejecuta este script desde Termux, no dentro de proot ni en otro terminal." ;;
esac
printf '%s' "$RELEASE" | grep -Eq '^[0-9]+\.[0-9]+\.[0-9]+$' || fail "Versión inválida: $RELEASE"
printf '%s' "$JOBS" | grep -Eq '^[1-9][0-9]*$' || fail "GDRIVE_BUILD_JOBS debe ser un entero positivo."
printf '%s' "$DISTRO" | grep -Eq '^[a-z0-9-]+$' || fail "Nombre de distribución proot inválido."
command -v pkg >/dev/null 2>&1 || fail "No se encontró pkg; instala Termux desde F-Droid o GitHub."

printf '\n[1/5] Instalando proot-distro en Termux...\n'
pkg update -y
pkg install -y proot-distro git

if ! proot-distro login "$DISTRO" -- true >/dev/null 2>&1; then
    printf '\n[2/5] Instalando %s ARM64 (puede tardar)...\n' "$DISTRO"
    proot-distro install "$DISTRO"
else
    printf '\n[2/5] La distribución %s ya está instalada.\n' "$DISTRO"
fi

printf '\n[3/5] Instalando el toolchain Rust y compilando gdrive %s para aarch64...\n' "$RELEASE"
printf 'La compilación puede tardar varios minutos en un teléfono. Trabajos paralelos: %s\n' "$JOBS"
proot-distro login "$DISTRO" -- env "GDRIVE_RELEASE=$RELEASE" "GDRIVE_BUILD_JOBS=$JOBS" bash -s <<'PROOT'
set -Eeuo pipefail
export DEBIAN_FRONTEND=noninteractive
apt-get update
apt-get install -y --no-install-recommends \
    bash ca-certificates cargo rustc git build-essential pkg-config libssl-dev python3
SOURCE_DIR="/tmp/gdrive-source-$GDRIVE_RELEASE"
rm -rf "$SOURCE_DIR"
git clone --depth 1 --branch "$GDRIVE_RELEASE" \
    https://github.com/glotlabs/gdrive.git "$SOURCE_DIR"
cargo install --locked --path "$SOURCE_DIR" --root /usr/local --jobs "$GDRIVE_BUILD_JOBS"
rm -rf "$SOURCE_DIR"
/usr/local/bin/gdrive version
PROOT

printf '\n[4/5] Creando el lanzador transparente para Termux...\n'
mkdir -p "$INSTALL_DIR"
LAUNCHER="$INSTALL_DIR/gdrive"
TEMP_LAUNCHER="$INSTALL_DIR/.gdrive.tmp"
cat > "$TEMP_LAUNCHER" <<EOF
#!$PREFIX/bin/bash
# Generated by termux_setup.sh. Credentials live inside the $DISTRO proot.
exec proot-distro login "$DISTRO" -- /usr/local/bin/gdrive "\$@"
EOF
chmod 700 "$TEMP_LAUNCHER"
mv "$TEMP_LAUNCHER" "$LAUNCHER"

printf '\n[5/5] Comprobando instalación...\n'
bash "$LAUNCHER" version
printf '\nInstalación ARM64 completada: %s\n' "$LAUNCHER"
printf 'Ahora ejecuta: python3 scripts/gdrive_skill.py doctor\n'
printf 'Para acceder a archivos del teléfono, ejecuta termux-setup-storage y usa rutas /sdcard/...\n'
